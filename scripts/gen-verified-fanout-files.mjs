#!/usr/bin/env node
// #470 / ledger D8 + #474: regenerate src/shared/verified-fanout-files.ts.
//   VERIFIED_FANOUT_FILES        = v1's references/ + scripts/ledger-set, BYTE-IDENTICAL to the frozen v1 (from <v1 dir>, or — no arg — the ones already in the module).
//   VERIFIED_FANOUT_V2_REFERENCES = the v2-only references/*.md, embedded from their SINGLE source dir src/shared/verified-fanout-refs/ (#474).
//   node --experimental-strip-types --no-warnings scripts/gen-verified-fanout-files.mjs [<path to v1 skills dir containing verified-fanout/>]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'src', 'shared', 'verified-fanout-files.ts');
const REFS_DIR = path.join(REPO, 'src', 'shared', 'verified-fanout-refs');
const V1_FILES = ['references/meta-rules.md', 'references/prose.md', 'references/traps.md', 'references/working-with-agents.md', 'scripts/ledger-set'];
const dir = process.argv[2];
const line = (rel, mode, text) => `  { path: ${JSON.stringify(rel)}, mode: 0o${mode.toString(8)}, content: ${JSON.stringify(text)} },`;

let v1;
if (dir) {
  v1 = V1_FILES.map((rel) => {
    const abs = path.join(dir, 'verified-fanout', rel);
    const buf = fs.readFileSync(abs);
    const text = buf.toString('utf8');
    if (Buffer.from(text, 'utf8').compare(buf) !== 0) throw new Error(`${rel} is not valid UTF-8 text — cannot embed byte-identically`);
    return line(rel, fs.statSync(abs).mode & 0o111 ? 0o755 : 0o644, text);
  });
} else {
  const { VERIFIED_FANOUT_FILES } = await import(pathToFileURL(OUT).href);
  v1 = V1_FILES.map((rel) => { const f = VERIFIED_FANOUT_FILES.find((x) => x.path === rel); if (!f) throw new Error(`${rel} missing from the current module — pass the v1 dir`); return line(rel, f.mode, f.content); });
}
const v2Names = fs.readdirSync(REFS_DIR).filter((n) => n.endsWith('.md')).sort();
if (v2Names.length === 0) throw new Error(`no *.md in ${REFS_DIR}`);
const v2 = v2Names.map((n) => {
  if (V1_FILES.includes(`references/${n}`)) throw new Error(`${n} collides with a v1 file name`);
  return line(`references/${n}`, 0o644, fs.readFileSync(path.join(REFS_DIR, n), 'utf8'));
});
const out = `// GENERATED by scripts/gen-verified-fanout-files.mjs — never edit by hand.
// VERIFIED_FANOUT_FILES: byte-identical to the frozen v1 skill (tag verified-fanout-v1-prose, ledger #471 D8); verified-fanout-skill.test.ts holds each file's sha256 to v1's SHA256SUMS.
// VERIFIED_FANOUT_V2_REFERENCES (#474): the v2-only situational references, embedded from src/shared/verified-fanout-refs/*.md (the single source); the test re-reads that dir and compares.
export interface BundledSkillFile { path: string; mode: number; content: string }

export const VERIFIED_FANOUT_FILES: readonly BundledSkillFile[] = [
${v1.join('\n')}
];

export const VERIFIED_FANOUT_V2_REFERENCES: readonly BundledSkillFile[] = [
${v2.join('\n')}
];
`;
fs.writeFileSync(OUT, out);
console.log(`wrote src/shared/verified-fanout-files.ts (${out.length} chars, ${v1.length} v1 files + ${v2.length} v2 references)`);

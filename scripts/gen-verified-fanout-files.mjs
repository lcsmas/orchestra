#!/usr/bin/env node
// #470 / ledger D8: regenerate src/shared/verified-fanout-files.ts — v1's references/ + scripts/ledger-set embedded BYTE-IDENTICAL (JSON string literals).
//   node scripts/gen-verified-fanout-files.mjs <path to v1 skills dir containing verified-fanout/>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) { console.error('usage: gen-verified-fanout-files.mjs <skills-v1 dir>'); process.exit(2); }
const FILES = ['references/meta-rules.md', 'references/prose.md', 'references/traps.md', 'references/working-with-agents.md', 'scripts/ledger-set'];
const entries = FILES.map((rel) => {
  const abs = path.join(dir, 'verified-fanout', rel);
  const buf = fs.readFileSync(abs);
  const text = buf.toString('utf8');
  if (Buffer.from(text, 'utf8').compare(buf) !== 0) throw new Error(`${rel} is not valid UTF-8 text — cannot embed byte-identically`);
  const mode = fs.statSync(abs).mode & 0o111 ? 0o755 : 0o644;
  return `  { path: ${JSON.stringify(rel)}, mode: 0o${mode.toString(8)}, content: ${JSON.stringify(text)} },`;
});
const out = `// GENERATED by scripts/gen-verified-fanout-files.mjs from the frozen v1 skill (tag verified-fanout-v1-prose) — never edit by hand.
// Byte-identical to v1 (ledger #471 D8): verified-fanout-skill.test.ts holds each file's sha256 to v1's SHA256SUMS.
export interface BundledSkillFile { path: string; mode: number; content: string }

export const VERIFIED_FANOUT_FILES: readonly BundledSkillFile[] = [
${entries.join('\n')}
];
`;
fs.writeFileSync(path.join(REPO, 'src', 'shared', 'verified-fanout-files.ts'), out);
console.log(`wrote src/shared/verified-fanout-files.ts (${out.length} chars, ${FILES.length} files)`);

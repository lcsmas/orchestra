#!/usr/bin/env python3
"""Accès mobile (#336): regenerate src/acces-mobile/icons-data.ts — the PWA icons, derived from the app icon (build/icon.png).
Full-bleed (iOS rounds the corners itself), 256 colours (~47 KB for the three). Needs Pillow.
Usage: python3 -I scripts/gen-acces-mobile-icons.py   (from the repo root)"""
import base64, io, os
from PIL import Image

ROOT = os.getcwd()
SRC = os.path.join(ROOT, 'build', 'icon.png')
OUT = os.path.join(ROOT, 'src', 'acces-mobile', 'icons-data.ts')
SIZES = {'180': 'apple-touch-icon', '192': 'icon-192', '512': 'icon-512'}
TOP, BOT = (0x16, 0x1B, 0x23), (0x0B, 0x0D, 0x10)  # the tile gradient of build/icon.svg


def background(size):
    im = Image.new('RGB', (size, size))
    px = im.load()
    for y in range(size):
        c = tuple(round(TOP[i] + (BOT[i] - TOP[i]) * y / (size - 1)) for i in range(3))
        for x in range(size):
            px[x, y] = c
    return im.convert('RGBA')


src = Image.open(SRC).convert('RGBA')
lines = ['// GENERATED by scripts/gen-acces-mobile-icons.py from build/icon.png — do not edit by hand (#336).']
for size, name in SIZES.items():
    n = int(size)
    art = src if n == src.width else src.resize((n, n), Image.LANCZOS)
    flat = Image.alpha_composite(background(n), art).convert('RGB')
    buf = io.BytesIO()
    flat.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).save(buf, format='PNG', optimize=True)
    const = 'ICON_%s_PNG_B64' % size
    lines.append("export const %s = '%s';" % (const, base64.b64encode(buf.getvalue()).decode()))
    print(name, size, len(buf.getvalue()), 'bytes')
open(OUT, 'w').write('\n'.join(lines) + '\n')
